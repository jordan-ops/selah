-- HYPRLAND CONFIG — ENTRY POINT                          --
-- Everything is split into section modules below; edit    --
-- those, not this file. `hyprctl reload` picks all of it   --
-- up.                                                      --
--                                                          --
-- Module map (order matters only where noted):             --
--   monitors.lua   outputs / scale                         --
--   programs.lua   shared app variables (required by       --
--                  binds.lua itself)                       --
--   autostart.lua  startup processes                       --
--   env.lua        environment variables + permissions     --
--   appearance.lua gaps, borders, blur, animations         --
--   layouts.lua    dwindle / master / scrolling tuning     --
--   misc.lua       misc flags                              --
--   input.lua      keyboard, mouse, gestures               --
--   binds.lua      all keybindings (quickshell + defaults) --
--   rules.lua      window / workspace rules                --
--   colors.lua     GENERATED by quickshell's               --
--                  scripts/switch-theme.sh — loaded        --
--                  automatically once a theme is applied   --
--   user-settings.lua GENERATED by quickshell's settings   --
--                  app (Apply) — loaded LAST, wins over    --
--                  the defaults above                      --
-- -- -- -- -- -- -- -- -- -- -- -- -- -- -- -- -- -- -- -- --

require("monitors")
require("autostart")
require("env")
require("appearance")
require("layouts")
require("misc")
require("input")
require("binds") -- requires programs.lua itself
require("rules")

force_default_wallpaper = 0
-- Theme colors, once switch-theme.sh has generated the file.
-- pcall so a missing file is not a config error.
local ok, err = pcall(require, "colors")
if not ok and not tostring(err):find("colors") then
	error(err)
end

-- User overrides written by quickshell's settings app (Apply) — required
-- LAST so they win over appearance/input defaults above. pcall so a
-- missing file (nothing applied yet) is not a config error. NOTE: the
-- find() pattern must escape '-' — in Lua patterns it is a quantifier,
-- and an unescaped one made the guard never match (config-error spam).
local uok, uerr = pcall(require, "user-settings")
if not uok and not tostring(uerr):find("user%-settings") then
	error(uerr)
end
