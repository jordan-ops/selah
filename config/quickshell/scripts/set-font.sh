#!/bin/sh
# set-font.sh <family> [size] — the local equivalent of omarchy-font-set,
# for the mechanisms that actually exist on THIS machine:
#
#   fontconfig  ~/.config/fontconfig/fonts.conf  (canonical: the shell,
#               Qt apps and anything resolving sans-serif/monospace read
#               here — same prepend_first trick omarchy uses)
#   GTK/GNOME   gsettings org.gnome.desktop.interface font-name,
#               document-font-name, monospace-font-name
#               (+ gtk-font-name patched into gtk-3.0/settings.ini)
#   kitty       font_family patched in place when kitty.conf exists
#
# Safe-write rules from omasettings: hand-written files get a first-touch
# .bak, are edited one value at a time, and the fontconfig write is
# validated with fc-match (rolled back on failure).
set -u

FAMILY="${1:-}"
SIZE="${2:-}"
[ -n "$FAMILY" ] || { echo "Usage: set-font.sh <family> [size]" >&2; exit 1; }

# size half: an explicit $2 wins, else KEEP the size gsettings holds
# right now — it used to default to 11, which silently reset a custom
# text size on every family pick (set-text-size.sh owns that number)
if [ -z "$SIZE" ]; then
  SIZE=$(gsettings get org.gnome.desktop.interface font-name 2>/dev/null \
    | sed -e "s/^['\"]//" -e "s/['\"]\$//" -e 's/.*[[:space:]]//')
  case "$SIZE" in ''|*[!0-9]*) SIZE=11 ;; esac
fi

fc-list | grep -Fqi -- "$FAMILY" || { echo "Font '$FAMILY' not found." >&2; exit 1; }

# ---- fontconfig: generated by us, but back up whatever was there ----
FC_DIR="$HOME/.config/fontconfig"
FC="$FC_DIR/fonts.conf"
mkdir -p "$FC_DIR"
if [ -f "$FC" ] && [ ! -f "$FC.bak" ]; then cp -p "$FC" "$FC.bak"; fi
cat > "$FC" <<XML
<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "fonts.dtd">
<fontconfig>
  <match target="pattern">
    <test name="family" qual="any"><string>sans-serif</string></test>
    <edit name="family" mode="prepend_first" binding="strong"><string>$FAMILY</string></edit>
  </match>
  <match target="pattern">
    <test name="family" qual="any"><string>monospace</string></test>
    <edit name="family" mode="prepend_first" binding="strong"><string>$FAMILY</string></edit>
  </match>
</fontconfig>
XML

# validate, then roll back — an unparseable fonts.conf is every app's
# font gone, so the file we just wrote must resolve before we keep it
if ! fc-match sans-serif >/dev/null 2>&1; then
  if [ -f "$FC.bak" ]; then cp -p "$FC.bak" "$FC"; else rm -f "$FC"; fi
  echo "fontconfig write failed validation; rolled back" >&2
  exit 1
fi

# ---- GTK + GNOME apps ----
gsettings set org.gnome.desktop.interface font-name "$FAMILY $SIZE" >/dev/null 2>&1 || true
gsettings set org.gnome.desktop.interface document-font-name "$FAMILY $SIZE" >/dev/null 2>&1 || true
gsettings set org.gnome.desktop.interface monospace-font-name "$FAMILY $SIZE" >/dev/null 2>&1 || true

# GTK3 settings.ini — single value, in place, first-touch .bak
INI="$HOME/.config/gtk-3.0/settings.ini"
if [ -f "$INI" ]; then
  if [ ! -f "$INI.bak" ]; then cp -p "$INI" "$INI.bak"; fi
  if grep -q '^gtk-font-name=' "$INI"; then
    sed -i "s/^gtk-font-name=.*/gtk-font-name=$FAMILY $SIZE/" "$INI"
  else
    printf 'gtk-font-name=%s %s\n' "$FAMILY" "$SIZE" >> "$INI"
  fi
fi

# GTK4 settings.ini — same single value, so GTK4 apps can't keep an older
# family the picker already replaced (this is where DejaVu used to linger)
INI4="$HOME/.config/gtk-4.0/settings.ini"
if [ -f "$INI4" ]; then
  if [ ! -f "$INI4.bak" ]; then cp -p "$INI4" "$INI4.bak"; fi
  if grep -q '^gtk-font-name=' "$INI4"; then
    sed -i "s/^gtk-font-name=.*/gtk-font-name=$FAMILY $SIZE/" "$INI4"
  else
    printf 'gtk-font-name=%s %s\n' "$FAMILY" "$SIZE" >> "$INI4"
  fi
fi

# ---- kitty — single value, in place, first-touch .bak, nudge running
# instances the way omarchy-font-set does (SIGUSR1 reloads the config)
KITTY="$HOME/.config/kitty/kitty.conf"
if [ -f "$KITTY" ]; then
  if [ ! -f "$KITTY.bak" ]; then cp -p "$KITTY" "$KITTY.bak"; fi
  if grep -qE '^[[:space:]]*font_family[[:space:]]+' "$KITTY"; then
    esc=$(printf '%s' "$FAMILY" | sed 's/[\\&/]/\\&/g')
    sed -i -E "s/^[[:space:]]*font_family[[:space:]].*/font_family $esc/" "$KITTY"
  else
    printf '\nfont_family %s\n' "$FAMILY" >> "$KITTY"
  fi
  pkill -USR1 kitty 2>/dev/null || true
fi

fc-cache -f >/dev/null 2>&1 || true

# remember what we set — SettingsDropdownRow reads gsettings first, this
# is the fallback for a session where dconf is unavailable
mkdir -p "$HOME/.local/state/quickshell"
printf '%s' "$FAMILY" > "$HOME/.local/state/quickshell/current-font"
exit 0
